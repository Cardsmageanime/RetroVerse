const assert=require("node:assert/strict");
const {Input,direction,connected}=require("./two_player_input.js");
const pad=(index,axis=0,up=false,down=false)=>({index,id:"Test Pad "+index,connected:true,axes:[0,axis],buttons:Array.from({length:16},(_,i)=>({pressed:i===12&&up||i===13&&down}))});
assert.equal(direction(pad(0,-0.8)),-1);
assert.equal(direction(pad(0,0.8)),1);
assert.equal(direction(pad(0,0.2)),0);
assert.equal(direction(pad(0,0,true)), -1);
assert.equal(direction(pad(0,0,false,true)),1);
assert.equal(direction(pad(0,0,true,true)),0);
const first=new Input(),second=new Input();
assert.equal(first.sample([pad(2,-.9),pad(1,.9)]).active,1);
assert.equal(first.sample([pad(2,-.9),pad(1,.9)]).direction,1);
assert.equal(first.select(2,[pad(2,-.9),pad(1,.9)]),true);
assert.equal(first.sample([pad(2,-.9),pad(1,.9)]).direction,-1);
assert.equal(second.sample([pad(5,.9)]).direction,1);
assert.equal(first.sample([pad(2,-.9),pad(1,.9)]).direction,-1);
assert.equal(first.select(9,[pad(1,0)]),false);
assert.equal(first.sample([]).active,null);
first.keyboard("ArrowUp",true);
assert.equal(first.sample([]).direction,-1);
first.keyboard("ArrowDown",true);
assert.equal(first.sample([]).direction,0);
first.keyboard("ArrowUp",false);
assert.equal(first.sample([]).direction,1);
assert.equal(first.changed({direction:1}),true);
assert.equal(first.changed({direction:1}),false);
assert.equal(first.changed({direction:0}),true);
first.reset();
assert.equal(first.sample([]).direction,0);
assert.equal(connected([null,pad(3),pad(1)])[0].index,1);
console.log("Two-player controller adapter tests passed");
